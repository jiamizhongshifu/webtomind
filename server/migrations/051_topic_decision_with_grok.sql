- 核心话题

### Step 2: 初筛过滤

从采集的素材中筛选 **15-20 个候选选题**。

**筛选标准**：
| 维度 | 通过条件 |
|------|----------|
| 时效性 | 24-48小时内热点优先 |
| 领域匹配 | AI/设计/产品/编程/变现 |
| 可写性 | 有足够素材支撑 |
| 去重 | 避免与常见内容重复 |

**淘汰条件**：
- 纯娱乐八卦
- 政治敏感话题
- 负面舆情
- 缺乏深度的流水新闻

### Step 3: 深度匹配

为每个候选选题匹配深度素材角度：

**角度来源**：
1. **方法论角度** - 是否可以结合知名方法论（如第一性原理、复利思维）
2. **名人观点** - 是否有行业大佬的相关观点可引用
3. **实操教程** - 是否可以转化为手把手教程
4. **工具测评** - 是否涉及可评测的工具

**优先匹配的专家领域**：
| 领域 | 代表人物 | 适用选题 |
|------|----------|----------|
| AI 产品 | Amjad Masad (Replit) | AI 编程工具 |
| 设计工具 | Dylan Field (Figma) | AI 设计工具 |
| 产品管理 | Brian Chesky (Airbnb) | 产品思维 |
| 内容创作 | Dan Koe | 写作方法论 |
| 创业投资 | Paul Graham | 创业思维 |
| 独立开发 | Pieter Levels | 一人公司 |

### Step 4: 综合评分（100分制）

**评分维度**：
| 维度 | 权重 | 评估要素 |
|------|------|----------|
| 时效性 | 25分 | 是否近期热点？有无时间窗口？ |
| 定位匹配 | 25分 | 是否匹配 AI/产品/效率 定位？ |
| 爆款潜力 | 20分 | HKR原则：Hook勾人 + Knowledge有料 + Resonance共鸣 |
| 深度素材 | 15分 | 是否有专家观点/方法论支撑？ |
| 差异化 | 15分 | 有无独特角度？是否容易同质化？ |

**内容类型加成**（数据验证）：
| 类型 | 加成 | 说明 |
|------|------|------|
| 实操教程 | **+15分** | 阅读+分享双高 |
| 名人方法论+工具 | **+10分** | 阅读量高 |
| 热点+教程结合 | **+5分** | 需24小时内发布 |
| 纯热点追踪 | **-10分** | 不推荐 |
| 纯观点分析 | **-15分** | 避免 |

**评分等级**：
| 分数 | 等级 | 建议 |
|------|------|------|
| 80+ | 强烈推荐 | 今天写，趁热度 |
