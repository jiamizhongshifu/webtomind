function printHelp() {
  console.log(`Usage: pnpm cf:dev:real-api [--no-build] [--port 4173]

Start the Cloudflare Worker locally with real API env from .env.local.

The script:
- derives ${localHyperdriveEnvName} when needed
- writes a temporary workers/.dev.vars for Wrangler local dev
- restores/removes workers/.dev.vars on exit

Options:
  --no-build   Skip pnpm build:cloudflare before starting Wrangler
  --port       Local Worker port (default: Wrangler default)
  --require-least-privilege
               Refuse the local postgres-owner fallback
  --help       Show this help text
`);
}

function loadLocalEnvFiles() {
  let loaded = 0;
  for (const file of envFiles) {
    const filePath = path.isAbsolute(file) ? file : path.join(root, file);
    if (!existsSync(filePath)) continue;
    const parsed = dotenv.parse(readFileSync(filePath, 'utf8'));
    loaded += 1;
    for (const [key, value] of Object.entries(parsed)) {
      if (file.includes('secrets/') || !process.env[key]) {
        process.env[key] = value;
      }
    }
  }

  if (loaded === 0) {
    throw new Error(
      'Missing local env files. Real Worker API dev needs .env.local, secrets/hyperdrive-readonly.env, or WEBTOMIND_ENV_FILE. Cloudflare auth is loaded from the canonical credential store.'
    );
  }
}

function usable(value) {
  const trimmed = String(value || '').trim();
  if (!trimmed || trimmed.includes('placeholder')) return '';
  if (trimmed.includes('your-') || trimmed.includes('your_')) return '';
  return trimmed;
}

function getEnv(...names) {
  for (const name of names) {
    const value = usable(process.env[name]);
    if (value) return value;
  }
  return '';
}

function getSupabaseProjectRef() {
  const explicit = getEnv('SUPABASE_PROJECT_REF');
  if (explicit) return explicit;

  const supabaseUrl = getEnv('SUPABASE_URL', 'VITE_SUPABASE_URL');
  if (!supabaseUrl) return '';
  return new URL(supabaseUrl).hostname.split('.')[0] || '';
}

function deriveHyperdriveLocalConnectionString() {
  for (const name of directHyperdriveEnvNames) {
    const configured = getEnv(name);
    if (configured) {
      return {
        value: configured,
        source: name,
        derivedFromPostgresPassword: false
      };
    }
  }

  const projectRef = getSupabaseProjectRef();
  const password = getEnv('SUPABASE_DB_PASSWORD');
  if (!projectRef || !password) {
    throw new Error(
      `Missing Hyperdrive local connection. Set ${localHyperdriveEnvName}, HYPERDRIVE_DIRECT_CONNECTION_STRING, or SUPABASE_URL + SUPABASE_DB_PASSWORD in .env.local.`
    );
  }

  const url = new URL(
    `postgresql://postgres@db.${projectRef}.supabase.co/postgres`
  );
  url.port = '5432';
  url.password = password;
  url.searchParams.set('sslmode', 'require');
  return {
    value: url.toString(),
    source: 'SUPABASE_DB_PASSWORD',
    derivedFromPostgresPassword: true
  };
}

function quoteDevVar(value) {
  const normalized = String(value);
  if (/[\r\n']/u.test(normalized)) {
    throw new Error(
      'Real Worker API env contains a value that cannot be encoded safely in .dev.vars.'
    );
  }
  const encoded = `'${normalized}'`;
  const decoded = dotenv.parse(`WEBTOMIND_VALUE=${encoded}\n`).WEBTOMIND_VALUE;
  if (decoded !== normalized) {
    throw new Error(
      'Real Worker API env failed the .dev.vars round-trip check.'
    );
  }
  return encoded;
}

function isGeneratedDevVars(filePath) {
  return (
    existsSync(filePath) &&
    readFileSync(filePath, 'utf8').startsWith(generatedDevVarsMarker)
  );
}

function recoverStaleGeneratedDevVars() {
  if (existsSync(devVarsBackupFile)) {
    if (!isGeneratedDevVars(devVarsBackupFile)) {
      throw new Error(
        `Refusing to start because ${path.basename(
          devVarsBackupFile
        )} contains a real previous configuration. Restore it manually before continuing.`
      );
    }
    unlinkSync(devVarsBackupFile);
  }
  if (isGeneratedDevVars(devVarsFile)) {
    unlinkSync(devVarsFile);
  }
}

function hasPoolerBootstrapUrl() {
  return poolerBootstrapEnvNames.some((name) => Boolean(getEnv(name)));
}

function warnIfPrivilegedHyperdriveConnection(connection) {
  try {
    const url = new URL(connection.value);
    if (decodeURIComponent(url.username) !== 'postgres') return;
    if (requireLeastPrivilege) {
      throw new Error(
        `Refusing postgres-owner Hyperdrive fallback because --require-least-privilege is set. Add HYPERDRIVE_DIRECT_CONNECTION_STRING, or set SUPABASE_SESSION_POOLER_URL and run pnpm cf:hyperdrive:readonly-role to generate one.`
      );
    }
    console.warn(
      '[cf:dev:real-api] Warning: using a postgres-owner Hyperdrive fallback for local dev. Prefer setting HYPERDRIVE_DIRECT_CONNECTION_STRING to the least-privilege readonly URL generated by scripts/setup-hyperdrive-readonly-role.mjs.'
    );
    if (connection.derivedFromPostgresPassword && !hasPoolerBootstrapUrl()) {
      console.warn(
        '[cf:dev:real-api] No Supabase Session Pooler URL is configured, so this machine cannot bootstrap the readonly role if Direct Postgres is unreachable over IPv6. Add SUPABASE_SESSION_POOLER_URL from Supabase Dashboard > Connect > Session Pooler, then run pnpm cf:hyperdrive:readonly-role.'
      );
    }
  } catch (error) {
    if (error instanceof Error) throw error;
    // Wrangler will surface malformed connection strings during startup.
  }
}

function writeTemporaryDevVars(connectionString) {
  recoverStaleGeneratedDevVars();
  if (existsSync(devVarsBackupFile)) {
    throw new Error(
      `Refusing to start because ${path.basename(
        devVarsBackupFile
      )} already exists. Remove it after checking no previous workers/.dev.vars needs restoring.`
    );
  }

  let hadOriginal = false;
  if (existsSync(devVarsFile)) {
    renameSync(devVarsFile, devVarsBackupFile);
    hadOriginal = true;
  }

  const lines = [
    generatedDevVarsMarker,
    '# It is gitignored and removed/restored when the process exits.',
    `${localHyperdriveEnvName}=${quoteDevVar(connectionString)}`,
    // 本地 R2 模拟器不包含图片工具模型对象，回源线上保证去除背景等
    // 本地工具可运行；生产部署不会写入此变量。
    `LOCAL_MODEL_ORIGIN=${quoteDevVar('https://webtomind.com')}`,
    // 本地 Wrangler 使用 watermarks:up 提供的 HTTP 服务，不启动生产容器。
    `WATERMARKS_SERVICE_MODE=${quoteDevVar('http')}`
  ];
  const written = new Set([
    localHyperdriveEnvName,
    'LOCAL_MODEL_ORIGIN',
    'WATERMARKS_SERVICE_MODE'
  ]);

  for (const key of workerEnvKeys) {
    const value = usable(process.env[key]);
    if (!value || written.has(key)) continue;
    lines.push(`${key}=${quoteDevVar(value)}`);
    written.add(key);
  }

  if (!written.has('SUPABASE_URL')) {
    const value = usable(process.env.VITE_SUPABASE_URL);
    if (value) lines.push(`SUPABASE_URL=${quoteDevVar(value)}`);
  }
  if (!written.has('SUPABASE_ANON_KEY')) {
    const value = usable(process.env.VITE_SUPABASE_ANON_KEY);
    if (value) lines.push(`SUPABASE_ANON_KEY=${quoteDevVar(value)}`);
  }

  writeFileSync(devVarsFile, `${lines.join('\n')}\n`, { mode: 0o600 });

  let cleaned = false;
  return () => {
    if (cleaned) return;
    cleaned = true;
    try {
      if (existsSync(devVarsFile)) unlinkSync(devVarsFile);
      if (hadOriginal && existsSync(devVarsBackupFile)) {
        renameSync(devVarsBackupFile, devVarsFile);
      }
    } catch (error) {
      console.error(
        `[cf:dev:real-api] Failed to clean temporary .dev.vars: ${
          error instanceof Error ? error.message : String(error)
        }`
      );
    }
  };
}

function describeConnection(connectionString) {
  const url = new URL(connectionString);
  return `${url.username || '<unknown-user>'}@${url.hostname}/${url.pathname.replace(/^\//u, '') || '<unknown-db>'}`;
}

function run(command, commandArgs) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, commandArgs, {
      cwd: root,
      env: process.env,
      stdio: 'inherit',
      shell: false
    });
    child.on('error', reject);
    child.on('exit', (code, signal) => {
      if (signal) {
        resolve({ code: 128, signal });
        return;
      }
      if (code === 0) {
        resolve({ code: 0, signal: null });
        return;
      }
      reject(
        new Error(
          `${command} ${commandArgs.join(' ')} failed with code ${code}`
        )
      );
    });
  });
}

async function main() {
  if (args.has('--help') || args.has('-h')) {
    printHelp();
    return;
  }

  if (
    requestedPort &&
    (!/^\d+$/u.test(requestedPort) ||
      Number(requestedPort) < 1 ||
      Number(requestedPort) > 65535)
  ) {
    throw new Error(`Invalid --port value: ${requestedPort}`);
  }
  if (portFlagIndex >= 0 && !requestedPort) {
    throw new Error('Missing value after --port.');
  }

  loadLocalEnvFiles();
  applyCloudflareGatewayRunCredential();
  const localMediaStorage = configureLocalMediaStorageEnv();
  const localR2MediaProxy = await startLocalR2MediaProxy({ root });
  process.env.LOCAL_R2_MEDIA_PROXY_URL = localR2MediaProxy.url;
  process.env.LOCAL_R2_MEDIA_PROXY_TOKEN = localR2MediaProxy.token;
  const connection = deriveHyperdriveLocalConnectionString();
  warnIfPrivilegedHyperdriveConnection(connection);
  const connectionString = connection.value;
  process.env[localHyperdriveEnvName] = connectionString;
  const cleanupDevVars = writeTemporaryDevVars(connectionString);
  const cleanup = () => {
    cleanupDevVars();
    void localR2MediaProxy.close();
  };
  for (const signal of ['SIGINT', 'SIGTERM']) {
    process.once(signal, () => {
      cleanup();
      process.kill(process.pid, signal);
    });
  }
  process.once('exit', cleanup);

  console.log(
    `[cf:dev:real-api] Hyperdrive local connection ready: ${describeConnection(
      connectionString
    )}`
  );
  console.log(
    `[cf:dev:real-api] Media storage ready: ${localMediaStorage.provider} (${localMediaStorage.source})`
  );
  console.log(
    `[cf:dev:real-api] Local R2 history fallback ready: ${localR2MediaProxy.url}`
  );
  if (!args.has('--no-build')) {
    console.log('[cf:dev:real-api] Building Cloudflare web assets...');
    await run('pnpm', ['build:cloudflare']);
  }

  console.log(
    `[cf:dev:real-api] Starting Wrangler with real Worker API${
      requestedPort ? ` on http://127.0.0.1:${requestedPort}` : ''
    }...`
  );
  // 本地联调：让 Tuzi/出图渠道直连，避免走本机代理导致的大请求偶发超时。
  // 生产环境（Cloudflare Worker 部署）不读取本机代理，不受影响。
  const localNoProxy = [
    'localhost',
    '127.0.0.1',
    '::1',
    '.tu-zi.com',
    '.chaojitudou.com',
    '.cdn-krill-ai.com',
    '.webtomind.com'
  ].join(',');
  const existingNoProxy = String(process.env.NO_PROXY || process.env.no_proxy || '').trim();
  process.env.NO_PROXY = existingNoProxy
    ? `${existingNoProxy},${localNoProxy}`
    : localNoProxy;
  const wranglerArgs = [
    'exec',
    'wrangler',
    'dev',
    '--config',
    wranglerConfig,
    '--log-level',
    process.env.WRANGLER_LOG_LEVEL || 'info'
  ];
  if (requestedPort) wranglerArgs.push('--port', requestedPort);
  await run('pnpm', wranglerArgs);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
