function parseArgs(argv) {
  const args = {
    manifest: MANIFEST_PATH,
    config: CONFIG_PATH,
    bucket: process.env.PROMPT_ASSETS_BUCKET || DEFAULT_BUCKET,
    dryRun: false,
    metadataOnly: false
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--manifest') args.manifest = argv[++i] || args.manifest;
    else if (arg === '--config') args.config = argv[++i] || args.config;
    else if (arg === '--bucket') args.bucket = argv[++i] || args.bucket;
    else if (arg === '--dry-run') args.dryRun = true;
    else if (arg === '--metadata-only') args.metadataOnly = true;
    else if (arg === '--help') {
      printHelp();
      process.exit(0);
    }
  }

  return args;
}

function printHelp() {
  console.log(`Usage:
  pnpm sync:prompt-assets
  node scripts/sync-prompt-assets.mjs --bucket studio-assets

Options:
  --manifest <path>    Manifest generated by prompt-assets script
  --config <path>      Batch config used to preserve operator display order
  --bucket <name>      Supabase Storage bucket, default studio-assets
  --metadata-only      Skip file upload and write URLs from manifest as-is
  --dry-run            Validate and print the sync plan without writing

Required env:
  SUPABASE_URL
  SUPABASE_SERVICE_ROLE_KEY
`);
}

async function loadDotEnv(filePath) {
  try {
    const content = await fs.readFile(filePath, 'utf8');
    content
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter((line) => line && !line.startsWith('#'))
      .forEach((line) => {
        const eq = line.indexOf('=');
        if (eq === -1) return;
        const key = line.slice(0, eq).trim();
        const rawValue = line.slice(eq + 1).trim();
        if (!key || process.env[key]) return;
        process.env[key] = rawValue.replace(/^["']|["']$/g, '');
      });
  } catch {
    // Optional env files are allowed to be absent.
  }
}

async function loadEnvFiles() {
  await loadDotEnv(path.join(ROOT, '.env.local'));
  await loadDotEnv(path.join(ROOT, '.env'));
  await loadDotEnv(path.join(ROOT, 'server/.env'));
}

async function readManifest(manifestPath) {
  const raw = await fs.readFile(path.resolve(ROOT, manifestPath), 'utf8');
  const manifest = JSON.parse(raw);
  if (!Array.isArray(manifest.assets)) {
    throw new Error(`Invalid manifest: ${manifestPath}`);
  }
  return manifest.assets;
}

async function readPublicationPolicy() {
  const raw = await fs.readFile(path.resolve(ROOT, PUBLICATION_POLICY_PATH), 'utf8');
  const policy = JSON.parse(raw);
  return new Set(policy.excludedAssetIds || []);
}

async function readSortOrderMap(configPath) {
  try {
    const raw = await fs.readFile(path.resolve(ROOT, configPath), 'utf8');
    const config = JSON.parse(raw);
    const orderMap = new Map();
    let cursor = 0;

    for (const batch of config.batches || []) {
      const slotOffset = SLOT_ORDER.indexOf(batch.slot) * 1000;
      for (const asset of batch.assets || []) {
        orderMap.set(asset.id, slotOffset + cursor);
        cursor += 1;
      }
    }

    return orderMap;
  } catch {
    return new Map();
  }
}

function assertAsset(asset) {
  if (
    !asset.id ||
    !asset.slot ||
    !asset.title ||
    !asset.prompt ||
    !asset.thumbnailUrl
  ) {
    throw new Error(`Invalid asset in manifest: ${JSON.stringify(asset)}`);
  }
  if (!SLOT_ORDER.includes(asset.slot)) {
    throw new Error(`Invalid slot for ${asset.id}: ${asset.slot}`);
  }
}

function resolveLocalAssetPath(asset) {
  if (!asset.thumbnailUrl.startsWith(LOCAL_ASSET_PREFIX)) {
    throw new Error(
      `Only local prompt-library URLs are uploadable: ${asset.thumbnailUrl}`
    );
  }
  return path.join(
    ROOT,
    'src/web/assets/prompt-library',
    asset.thumbnailUrl.slice(LOCAL_ASSET_PREFIX.length)
  );
}

function getStoragePath(asset) {
  const ext = path.extname(asset.thumbnailUrl) || '.webp';
  return `prompt-library/${asset.slot}/${asset.id}${ext}`;
}

function getSortOrder(asset, index, orderMap) {
  return (
    orderMap.get(asset.id) ?? SLOT_ORDER.indexOf(asset.slot) * 1000 + index
  );
}

async function uploadAsset({ supabase, bucket, asset }) {
  const localPath = resolveLocalAssetPath(asset);
  const buffer = await fs.readFile(localPath);
  const storagePath = getStoragePath(asset);
  const { error } = await supabase.storage
    .from(bucket)
    .upload(storagePath, buffer, {
      cacheControl: '31536000',
      contentType: 'image/webp',
      upsert: true
    });

  if (error) {
    throw new Error(`Upload failed for ${asset.id}: ${error.message}`);
  }

  const { data } = supabase.storage.from(bucket).getPublicUrl(storagePath);
  return versionPromptAssetPublicUrl(data.publicUrl, buffer);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  await loadEnvFiles();

  const manifestAssets = await readManifest(args.manifest);
  const excludedAssetIds = await readPublicationPolicy();
  const assets = manifestAssets.filter((asset) => !excludedAssetIds.has(asset.id));
  const sortOrderMap = await readSortOrderMap(args.config);
  assets.forEach(assertAsset);

  console.log(`[prompt-assets-sync] assets=${assets.length}`);
  console.log(`[prompt-assets-sync] bucket=${args.bucket}`);
  console.log(`[prompt-assets-sync] dryRun=${args.dryRun}`);
  console.log(`[prompt-assets-sync] metadataOnly=${args.metadataOnly}`);

  if (args.dryRun) {
    assets.forEach((asset, index) => {
      console.log(
        `${String(index + 1).padStart(2, '0')} ${asset.slot}/${asset.id} -> ${getStoragePath(asset)}`
      );
    });
    return;
  }

  const supabaseUrl = process.env.SUPABASE_URL;
  const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!supabaseUrl || !serviceKey) {
    throw new Error('SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are required.');
  }

  const supabase = createClient(supabaseUrl, serviceKey, {
    auth: { persistSession: false }
  });

  const records = [];
  for (const [index, asset] of assets.entries()) {
    const publicUrl = args.metadataOnly
      ? asset.thumbnailUrl
      : await uploadAsset({ supabase, bucket: args.bucket, asset });

    records.push({
      id: asset.id,
      slot: asset.slot,
      title: asset.title,
      subtitle: asset.subtitle || '',
      prompt: asset.prompt,
      negative_prompt: asset.negativePrompt || null,
      tags: asset.tags || [],
      thumbnail_url: publicUrl,
      source_batch_id: asset.sourceBatchId || null,
      provider: 'prompt-assets-sync',
      visual: VISUAL_BY_SLOT[asset.slot] || {},
      metadata: {
        localThumbnailUrl: asset.thumbnailUrl,
        storageBucket: args.metadataOnly ? null : args.bucket,
        storagePath: args.metadataOnly ? null : getStoragePath(asset)
      },
      sort_order: getSortOrder(asset, index, sortOrderMap),
      is_published: true
    });

    console.log(`[prompt-assets-sync] prepared=${asset.id}`);
  }

  const { error } = await supabase
    .from('prompt_assets')
    .upsert(records, { onConflict: 'id' });

  if (error) {
    throw new Error(`Database upsert failed: ${error.message}`);
  }

  if (excludedAssetIds.size > 0) {
    const { error: unpublishError } = await supabase
      .from('prompt_assets')
      .update({ is_published: false })
      .in('id', [...excludedAssetIds]);
    if (unpublishError) {
      throw new Error(`Failed to unpublish superseded assets: ${unpublishError.message}`);
    }
  }

  const publishedIds = new Set(records.map((record) => record.id));
  const { data: existingPublicAssets, error: existingAssetsError } =
    await supabase
      .from('prompt_assets')
      .select('id')
      .is('owner_user_id', null)
      .eq('is_published', true);
  if (existingAssetsError) {
    throw new Error(
      `Failed to load existing public assets: ${existingAssetsError.message}`
    );
  }
  const orphanedIds = (existingPublicAssets || [])
    .map((asset) => asset.id)
    .filter((id) => !publishedIds.has(id));
  for (let index = 0; index < orphanedIds.length; index += 100) {
    const chunk = orphanedIds.slice(index, index + 100);
    const { error: orphanedError } = await supabase
      .from('prompt_assets')
      .update({ is_published: false })
      .in('id', chunk);
    if (orphanedError) {
      throw new Error(
        `Failed to unpublish orphaned assets: ${orphanedError.message}`
      );
    }
  }

  console.log(`[prompt-assets-sync] upserted=${records.length}`);
  console.log(`[prompt-assets-sync] unpublished=${excludedAssetIds.size}`);
  console.log(`[prompt-assets-sync] orphaned=${orphanedIds.length}`);
}

main().catch((error) => {
  console.error(
    `[prompt-assets-sync] ${error instanceof Error ? error.message : error}`
  );
  process.exit(1);
});
